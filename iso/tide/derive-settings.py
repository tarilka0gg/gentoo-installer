#!/usr/bin/env python3
"""derive-settings.py <fish_variables> > tide/tide-live.fish

Turns the tide settings of a fish_variables file into global `set` lines for /etc/fish/conf.d. The layout (items, separators, icons)
is kept; every hex colour becomes an ANSI colour name, so the prompt is drawn in the terminal's palette (in the live image: the colours
Noctalia generates from the wallpaper) instead of fixed RGB values.
"""
import re, sys

NAMES = {  # the author's palette -> the nearest role in a terminal palette
    "3B342B": "black", "E9C87E": "yellow", "C9B896": "white", "9C8B66": "brblack", "F2EDD8": "brwhite",
    "BD5636": "red", "8A6D2F": "yellow", "7D8278": "brblack", "93988C": "white", "5C6B6F": "cyan",
}
out = ["# Generated by iso/tide/derive-settings.py: tide settings with terminal-palette colours.", "set -g VIRTUAL_ENV_DISABLE_PROMPT true"]
for line in open(sys.argv[1], encoding="utf-8"):
    m = re.match(r"SETUVAR (_?tide_[A-Za-z0-9_]+):(.*)$", line.rstrip("\n"))
    if not m:
        continue
    name, val = m.groups()
    if re.fullmatch(r"_tide_(right_)?prompt_\d+", name):
        continue
    if name in ("_tide_left_items", "_tide_right_items"):
        continue  # rebuilt by tide itself (_tide_cache_variables)
    if re.fullmatch(r"[0-9A-Fa-f]{6}", val):
        val = NAMES.get(val.upper(), "white")
    # fish_variables escapes (\xNN, \uNNNN); \x1e separates list elements, \x1d stands for an empty element
    val = re.sub(r"\\(x[0-9a-fA-F]{2}|u[0-9a-fA-F]{4}|U[0-9a-fA-F]{8})", lambda e: chr(int(e.group(1)[1:], 16)), val)
    if name == "tide_right_prompt_items":   # no "root@host" in the live session: the prompt is the same as the author's
        val = "\x1e".join(x for x in val.split("\x1e") if x != "context")
    items = ["" if x == "\x1d" else x for x in val.split("\x1e")] if val else []
    out.append("set -g %s %s" % (name, " ".join("'" + x.replace("\\", "\\\\").replace("'", "\\'") + "'" for x in items)))
print("\n".join(out))
